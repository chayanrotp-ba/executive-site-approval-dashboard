const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium,executablePath}=require('./executive-browser-test.cjs');

(async()=>{
 const profile=fs.mkdtempSync(path.resolve(__dirname,'../tmp/executive-history-test-'));
 const url=process.env.EXECUTIVE_TEST_URL||pathToFileURL(path.resolve(__dirname,'../executive_dashboard_v13_master_history.html')).href;
 let context=await chromium.launchPersistentContext(profile,{executablePath,headless:true,acceptDownloads:true,downloadsPath:path.resolve(__dirname,'../tmp'),viewport:{width:1440,height:1000}});
 let page=context.pages()[0];
 const errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 await page.goto(url);
 assert.equal(await page.locator('#rows tr').count(),85);
 assert.equal(await page.locator('#approvedTotal').textContent(),'0');
 assert.equal(await page.locator('.history-nav').evaluate(el=>getComputedStyle(el).display),'flex');
 await page.locator('#rows [data-approval-key]').first().click();
 await page.locator('#rows [data-approval-key]').nth(1).click();
 await page.locator('#roundNote').fill('ทดสอบรอบแรก');
 await page.locator('#provinceFilter').selectOption({label:'ขอนแก่น'});
 assert.ok(await page.locator('#rows tr').count()<85);
 await page.locator('#saveRound').click();
 await page.waitForFunction(()=>document.querySelector('#saveStatus').textContent.startsWith('บันทึกสำเร็จ'));
 await page.locator('#masterNav').click();
 await page.waitForFunction(()=>document.querySelectorAll('#historyRows [data-history-action="view"]').length===1);
 await page.locator('[data-history-action="view"]').click();
 assert.equal(await page.locator('#historyDetailRows tr').count(),85);
 assert.equal(await page.locator('#historyDetailRows .approved').count(),2);
 await page.screenshot({path:path.resolve(__dirname,'../tmp/executive-master-history.png'),fullPage:true});
 await page.reload();
 await page.waitForFunction(()=>document.querySelectorAll('#historyRows [data-history-action="view"]').length===1);
 await page.locator('#dashboardNav').click();
 assert.equal(await page.locator('#approvedTotal').textContent(),'0');
 assert.equal(await page.locator('#roundNote').inputValue(),'');
 assert.equal(await page.locator('#rows tr').count(),85);
 await page.locator('#rows [data-approval-key]').nth(2).click();
 await page.locator('#roundNote').fill('ทดสอบรอบสอง <script>');
 await page.locator('#saveRound').click();
 await page.waitForFunction(()=>document.querySelector('#saveStatus').textContent.startsWith('บันทึกสำเร็จ'));
 await page.locator('#masterNav').click();
 await page.waitForFunction(()=>document.querySelectorAll('#historyRows [data-history-action="view"]').length===2);
 await page.locator('[data-history-action="view"]').first().click();
 assert.equal(await page.locator('#historyDetailRows .approved').count(),1);
 const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#exportHistory').click()]);
 const exported=JSON.parse(fs.readFileSync(await download.path(),'utf8'));
 assert.equal(exported.rounds.length,2);
 assert.ok(exported.rounds.every(r=>r.rows.length===85&&!Number.isNaN(Date.parse(r.savedAt))));
 await page.locator('#historySearch').fill('รอบแรก');
 assert.equal(await page.locator('[data-history-action="view"]').count(),1);
 await page.locator('#historySearch').fill('');
 page.once('dialog',dialog=>dialog.dismiss());
 await page.locator('[data-history-action="delete"]').first().click();
 assert.equal(await page.locator('[data-history-action="view"]').count(),2);
 page.once('dialog',dialog=>dialog.accept());
 await page.locator('[data-history-action="delete"]').first().click();
 await page.waitForFunction(()=>document.querySelectorAll('#historyRows [data-history-action="view"]').length===1);
 await page.locator('[data-history-action="view"]').click();
 assert.equal(await page.locator('#historyDetailRows .approved').count(),2);
 await page.locator('#dashboardNav').click();
 assert.equal(await page.locator('#approvedTotal').textContent(),'1');
 // Storage failure must retain the round and must never report success.
 await page.evaluate(()=>{window.originalHistoryTransaction=historyTransaction;historyTransaction=async()=>{throw new Error('test quota failure');};});
 await page.locator('#saveRound').click();
 await page.waitForFunction(()=>document.querySelector('#saveStatus').textContent.startsWith('บันทึกไม่สำเร็จ'));
 assert.equal(await page.locator('#approvedTotal').textContent(),'1');
 await page.evaluate(()=>{historyTransaction=window.originalHistoryTransaction;});
 await page.screenshot({path:path.resolve(__dirname,'../tmp/executive-dashboard-history.png'),fullPage:true});
 assert.deepEqual(errors,[]);
 await context.close();
 context=await chromium.launchPersistentContext(profile,{executablePath,headless:true});
 page=context.pages()[0];
 await page.goto(url+'#master');
 await page.waitForFunction(()=>document.querySelectorAll('#historyRows [data-history-action="view"]').length===1);
 await page.locator('#dashboardNav').click();
 assert.equal(await page.locator('#approvedTotal').textContent(),'0');
 await page.locator('#masterNav').click();
 page.once('dialog',dialog=>dialog.accept());
 await page.locator('[data-history-action="delete"]').click();
 await page.waitForFunction(()=>document.querySelector('#historyRows').textContent.includes('ยังไม่มีประวัติ'));
 await page.reload();
 await page.waitForFunction(()=>document.querySelector('#historyRows').textContent.includes('ยังไม่มีประวัติ'));
 await context.close();
 console.log('PASS: 85-site snapshots, filtered save, separate rounds, refresh reset, browser-restart persistence, history detail/search/export, delete/cancel, storage failure, delete persistence; no browser errors.');
})().catch(error=>{console.error(error);process.exit(1);});
