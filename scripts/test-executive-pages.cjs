const fs=require('node:fs');
const path=require('node:path');
const http=require('node:http');
const assert=require('node:assert/strict');
const {chromium,executablePath}=require('./executive-browser-test.cjs');
(async()=>{
 const html=fs.readFileSync(path.resolve(__dirname,'../.pages-dist/index.html'),'utf8');
 const server=http.createServer((req,res)=>{if(req.url.startsWith('/executive-site-approval-dashboard/')){res.writeHead(200,{'Content-Type':'text/html; charset=utf-8'});res.end(html);}else{res.writeHead(404);res.end();}});
 await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
 const browser=await chromium.launch({executablePath,headless:true});
 const page=await browser.newPage();const errors=[],api=[];
 page.on('pageerror',error=>errors.push(error.message));page.on('request',req=>{if(req.url().includes('/api/'))api.push(req.url());});
 await page.goto('http://127.0.0.1:'+server.address().port+'/executive-site-approval-dashboard/');
 assert.equal(await page.locator('#rows tr').count(),85);
 assert.equal(await page.locator('#saveRound').isVisible(),false);
 assert.equal(await page.locator('#imageNav').isVisible(),false);
 await page.locator('#representativeFilter').selectOption('representative');assert.equal(await page.locator('#rows tr').count(),20);
 await page.locator('#basinFilter').selectOption('ลุ่มน้ำชี');assert.equal(await page.locator('#rows tr').count(),2);
 await page.locator('#rows .btn-detail').first().click();assert.match(await page.locator('#dTitle').textContent(),/บ้านหัน/);
 assert.equal(await page.locator('.drawer-approval').isVisible(),false);await page.locator('#closeBtn').click();
 await page.evaluate(()=>{setApprovedByKey('KKN-AWS-02',true);approveFilteredRows();saveRound();});
 assert.equal(await page.evaluate(()=>Object.keys(approvalState).length),0);
 assert.equal(await page.evaluate(async()=> (await indexedDB.databases()).length),0);
 await page.goto('http://127.0.0.1:'+server.address().port+'/executive-site-approval-dashboard/#master');
 assert.equal(await page.locator('#dashboardView').isVisible(),true);
 assert.deepEqual(api,[]);assert.deepEqual(errors,[]);
 await browser.close();await new Promise(resolve=>server.close(resolve));
 console.log('PASS: Pages view-only artifact, project subpath, 85 sites/20 representatives, basin filters/details, no API calls/database writes or approval mutations.');
})().catch(error=>{console.error(error);process.exit(1);});
